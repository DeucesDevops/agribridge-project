#!/usr/bin/env python3
"""Reapply the edits kOps does not keep, then split the render into modules.

kOps writes one kubernetes.tf. This script removes provider blocks, points the
launch templates at the AMI data source, drops the public object ACL, replaces
the placeholder zone id, and distributes resources:

  terraform/modules/network/main.tf          VPC, subnets, routes
  terraform/modules/network/outputs.tf
  terraform/modules/cluster/main.tf          control plane, node groups, add-ons
  terraform/modules/cluster/iam.tf           node and control-plane IAM
  terraform/modules/cluster/security-groups.tf
  terraform/modules/cluster/outputs.tf

The cluster module receives VPC and subnet ids as variables. kops/cluster.yaml
uses public subnets, so the network module has an internet gateway and no NAT.
"""

import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CLUSTER = REPO / "terraform" / "modules" / "cluster"
NETWORK = REPO / "terraform" / "modules" / "network"
GENERATED = CLUSTER / "kubernetes.tf"

HEADER = (
    "# Generated by kOps 1.36.2: kops update cluster --target=terraform.\n"
    "# scripts/render-kops-terraform.sh refreshes this file from kops/cluster.yaml\n"
    "# and reapplies scripts/patch_kops_terraform.py.\n"
    "# kops/cluster.yaml uses public subnets, so routes go to the internet gateway.\n"
    "# There is no NAT gateway.\n\n"
)

AMI = """# The image name is the one in kops/cluster.yaml. Looking it up here means a
# refreshed kOps render does not have to bake in an AMI id from the account
# that happened to generate the files.
data "aws_ami" "kops_node" {
  most_recent = true
  owners      = ["099720109477"]

  filter {
    name   = "name"
    values = ["ubuntu/images/hvm-ssd-gp3/ubuntu-noble-24.04-amd64-server-20260714"]
  }

  filter {
    name   = "virtualization-type"
    values = ["hvm"]
  }
}
"""

NETWORK_TYPES = {
    "aws_vpc",
    "aws_subnet",
    "aws_internet_gateway",
    "aws_egress_only_internet_gateway",
    "aws_nat_gateway",
    "aws_eip",
    "aws_route",
    "aws_route_table",
    "aws_route_table_association",
    "aws_vpc_dhcp_options",
    "aws_vpc_dhcp_options_association",
}
IAM_TYPES = {
    "aws_iam_instance_profile",
    "aws_iam_openid_connect_provider",
    "aws_iam_policy",
    "aws_iam_role",
    "aws_iam_role_policy",
    "aws_iam_role_policy_attachment",
}
SECURITY_GROUP_TYPES = {
    "aws_security_group",
    "aws_security_group_rule",
}
BLOCK_RE = re.compile(
    r"^(locals|output|resource|data|variable|terraform|provider)\b[^\n]*\{",
    re.M,
)


def find_matching_brace(text, open_index):
    depth = 0
    i = open_index
    in_string = False
    escape = False
    quote = ""
    while i < len(text):
        char = text[i]
        if in_string:
            if escape:
                escape = False
            elif char == "\\":
                escape = True
            elif char == quote:
                in_string = False
        else:
            if char in ('"', "'"):
                in_string = True
                quote = char
            elif char == "{":
                depth += 1
            elif char == "}":
                depth -= 1
                if depth == 0:
                    return i
        i += 1
    raise ValueError("unbalanced brace in kOps Terraform")


def parse_blocks(text):
    blocks = []
    cursor = 0
    while True:
        match = BLOCK_RE.search(text, cursor)
        if not match:
            break
        open_brace = match.end() - 1
        close = find_matching_brace(text, open_brace)
        raw = text[match.start() : close + 1]
        kind = match.group(1)
        header = text[match.start() : open_brace]
        blocks.append((kind, header, raw))
        cursor = close + 1
    return blocks


def resource_identity(header):
    match = re.match(r'resource\s+"([^"]+)"\s+"([^"]+)"', header.strip())
    if not match:
        raise ValueError(f"could not parse resource header: {header!r}")
    return match.group(1), match.group(2)


def patch_text(text):
    start = text.find('provider "aws" {')
    resource = text.find('resource "aws_autoscaling_group"')
    if start != -1 and resource != -1 and start < resource:
        text = text[:start] + text[resource:]
    text = text.replace(
        'image_id      = "ami-',
        "image_id      = data.aws_ami.kops_node.id  # patched from ami-",
    )
    lines = []
    for line in text.splitlines(keepends=True):
        if "data.aws_ami.kops_node.id  # patched from ami-" in line:
            line = "  image_id      = data.aws_ami.kops_node.id\n"
        if line.strip() == 'acl                    = "public-read"':
            continue
        lines.append(line)
    return "".join(lines)


def rewrite_network_refs(text, vpc_name, subnets, route_table_name):
    text = text.replace(f"aws_vpc.{vpc_name}.ipv6_cidr_block", "var.vpc_ipv6_cidr_block")
    text = text.replace(f"aws_vpc.{vpc_name}.cidr_block", "var.vpc_cidr_block")
    text = text.replace(f"aws_vpc.{vpc_name}.id", "var.vpc_id")
    for zone, name in subnets:
        text = text.replace(
            f"aws_subnet.{name}.id",
            f'var.public_subnet_ids["{zone}"]',
        )
    if route_table_name:
        text = text.replace(
            f"aws_route_table.{route_table_name}.id",
            "var.public_route_table_id",
        )
    return text


def join_blocks(blocks):
    return "\n\n".join(blocks).rstrip() + "\n"


def write(path, text):
    path.write_text(text)
    print(f"wrote {path.relative_to(REPO)}")


def split(text):
    blocks = parse_blocks(text)
    network = []
    iam = []
    security_groups = []
    main = []
    outputs = []
    vpc_name = None
    subnets = []
    route_table_name = None

    for kind, header, raw in blocks:
        if kind in ("terraform", "provider", "variable"):
            continue
        if kind == "locals":
            main.append(raw)
            continue
        if kind == "output":
            outputs.append(raw)
            continue
        if kind == "data":
            main.append(raw)
            continue
        if kind != "resource":
            raise ValueError(f"unexpected block {kind}")
        resource_type, name = resource_identity(header)
        if resource_type == "aws_vpc":
            vpc_name = name
        elif resource_type == "aws_subnet":
            zone = re.search(r'availability_zone\s+=\s+"([^"]+)"', raw)
            if not zone:
                raise ValueError(f"subnet {name} has no availability zone")
            subnets.append((zone.group(1), name))
        elif resource_type == "aws_route_table":
            route_table_name = name
        if resource_type in NETWORK_TYPES:
            network.append(raw)
        elif resource_type in IAM_TYPES:
            iam.append(raw)
        elif resource_type in SECURITY_GROUP_TYPES:
            security_groups.append(raw)
        else:
            main.append(raw)

    if not vpc_name:
        raise ValueError("kOps render has no VPC")
    if not subnets:
        raise ValueError("kOps render has no subnets")

    def rewritten(items):
        return [
            rewrite_network_refs(block, vpc_name, subnets, route_table_name)
            for block in items
        ]

    network_main = HEADER + join_blocks(network)
    subnet_map = "\n".join(
        f'    "{zone}" = aws_subnet.{name}.id' for zone, name in subnets
    )
    subnet_list = ", ".join(f"aws_subnet.{name}.id" for _, name in subnets)
    network_outputs = f'''output "vpc_id" {{
  description = "VPC created for the kOps cluster."
  value       = aws_vpc.{vpc_name}.id
}}

output "vpc_cidr_block" {{
  description = "IPv4 CIDR of the VPC."
  value       = aws_vpc.{vpc_name}.cidr_block
}}

output "vpc_ipv6_cidr_block" {{
  description = "IPv6 CIDR AWS assigns to the VPC."
  value       = aws_vpc.{vpc_name}.ipv6_cidr_block
}}

output "public_subnet_ids" {{
  description = "Public subnet ids keyed by availability zone. Nodes use these subnets directly. There is no NAT gateway."
  value = {{
{subnet_map}
  }}
}}

output "node_subnet_ids" {{
  description = "Public subnet ids in availability-zone order."
  value       = [{subnet_list}]
}}

output "public_route_table_id" {{
  description = "Route table whose default routes send traffic to the internet gateway."
  value       = aws_route_table.{route_table_name}.id
}}
'''
    cluster_main = (
        "# Generated by kOps, then split by scripts/patch_kops_terraform.py.\n"
        "# Control plane, node groups, launch templates, and cluster add-ons.\n\n"
        + AMI
        + "\n"
        + join_blocks(rewritten(main))
    )
    cluster_iam = (
        "# Generated by kOps, then split by scripts/patch_kops_terraform.py.\n"
        "# Control-plane role, node role, and the IRSA roles kOps renders.\n\n"
        + join_blocks(rewritten(iam))
    )
    cluster_sg = (
        "# Generated by kOps, then split by scripts/patch_kops_terraform.py.\n"
        "# Security groups for the control plane and the nodes.\n\n"
        + join_blocks(rewritten(security_groups))
    )
    cluster_outputs = (
        "# Generated by kOps, then split by scripts/patch_kops_terraform.py.\n\n"
        + join_blocks(rewritten(outputs))
    )

    write(NETWORK / "main.tf", network_main)
    write(NETWORK / "outputs.tf", network_outputs)
    write(CLUSTER / "main.tf", cluster_main)
    write(CLUSTER / "iam.tf", cluster_iam)
    write(CLUSTER / "security-groups.tf", cluster_sg)
    write(CLUSTER / "outputs.tf", cluster_outputs)


def main():
    if not GENERATED.exists():
        raise SystemExit(
            "terraform/modules/cluster/kubernetes.tf is missing. "
            "Run scripts/render-kops-terraform.sh so kOps can write it."
        )
    text = patch_text(GENERATED.read_text())
    split(text)
    for path in (CLUSTER / "data").glob("*"):
        raw = path.read_text()
        updated = raw.replace(
            "arn:aws:route53:::hostedzone/ZAGRIBRIDGE01",
            "arn:aws:route53:::hostedzone/*",
        )
        if updated != raw:
            path.write_text(updated)
    GENERATED.unlink()
    print(f"removed {GENERATED.relative_to(REPO)}")


if __name__ == "__main__":
    main()
